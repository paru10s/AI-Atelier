def get_products_by_category(category):
    """
    Return all products belonging to a particular category.
    Example categories:
    basin, faucet, toilet, shower
    """

    return [
        product
        for product in KOHLER_PRODUCTS
        if product["category"].lower() == category.lower()
    ]


def get_products_within_budget(category, max_price):
    """
    Return products from a category that are within
    the specified maximum price.
    """

    return [
        product
        for product in KOHLER_PRODUCTS
        if product["category"].lower() == category.lower()
        and product["price"] <= max_price
    ]


def get_product_by_sku(sku):
    """
    Find one product using its Kohler SKU.
    """

    for product in KOHLER_PRODUCTS:

        if product["sku"].lower() == sku.lower():
            return product

    return None